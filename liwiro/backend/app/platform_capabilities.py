def _copy_capability(record: dict[str, Any]) -> dict[str, Any]:
    return {
        **record,
        "stageSupport": list(record.get("stageSupport") or []),
        "supports": dict(record.get("supports") or {}),
        "permissions": [str(item).strip() for item in list(record.get("permissions") or []) if str(item).strip()],
        "manualLinks": [
            {"title": str(item.get("title") or "").strip(), "href": str(item.get("href") or "").strip()}
            for item in list(record.get("manualLinks") or [])
            if isinstance(item, dict) and str(item.get("title") or "").strip() and str(item.get("href") or "").strip()
        ],
    }


def list_platform_capabilities(
    *,
    client: str = "",
    surface_id: str = "",
    executable_only: bool = False,
) -> list[dict[str, Any]]:
    normalized_client = str(client or "").strip().lower()
    normalized_surface = str(surface_id or "").strip().lower()
    items: list[dict[str, Any]] = []
    for raw in _PLATFORM_CAPABILITIES:
        record = _copy_capability(raw)
        if normalized_client and not bool((record.get("supports") or {}).get(normalized_client)):
            continue
        if normalized_surface and str(record.get("surfaceId") or "").strip().lower() != normalized_surface:
            continue
        if executable_only and str(record.get("executionMode") or "").strip().lower() not in {"page", "server"}:
            continue
        items.append(record)
    return items


def get_platform_capability(capability_id: str) -> dict[str, Any] | None:
    normalized = str(capability_id or "").strip()
    if not normalized:
        return None
    for record in _PLATFORM_CAPABILITIES:
        if str(record.get("capabilityId") or "").strip() == normalized:
            return _copy_capability(record)
    return None


def capability_id_for_artifact(kind: str, action: str = "") -> str:
    normalized_kind = str(kind or "").strip()
    if normalized_kind == "service-manager-action":
        return _SERVICE_MANAGER_ACTION_CAPABILITY_IDS.get(str(action or "").strip().lower(), "")
    return _ARTIFACT_CAPABILITY_IDS.get(normalized_kind, "")
