from __future__ import annotations

from typing import Any


def _links(*items: tuple[str, str]) -> list[dict[str, str]]:
    return [{"title": str(title).strip(), "href": str(href).strip()} for title, href in items if str(title).strip() and str(href).strip()]


def _capability(
    capability_id: str,
    *,
    title: str,
    summary: str,
    subsystem: str,
    surface_id: str,
    surface_path: str,
    action_family: str,
    execution_mode: str,
    stage_support: list[str],
    supports: dict[str, bool] | None = None,
    permissions: list[str] | None = None,
    risk_level: str = "low",
    artifact_kind: str = "",
    manual_links: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    return {
        "capabilityId": capability_id,
        "title": title,
        "summary": summary,
        "subsystem": subsystem,
        "surfaceId": surface_id,
        "surfacePath": surface_path,
        "actionFamily": action_family,
        "executionMode": execution_mode,
        "stageSupport": list(stage_support),
        "supports": {
            "verse": bool((supports or {}).get("verse", True)),
            "cli": bool((supports or {}).get("cli", True)),
            "ui": bool((supports or {}).get("ui", True)),
        },
        "permissions": [str(item).strip() for item in list(permissions or []) if str(item).strip()],
        "riskLevel": str(risk_level or "low").strip().lower(),
        "artifactKind": str(artifact_kind or "").strip(),
        "manualLinks": [
            {"title": str(item.get("title") or "").strip(), "href": str(item.get("href") or "").strip()}
            for item in list(manual_links or [])
            if isinstance(item, dict) and str(item.get("title") or "").strip() and str(item.get("href") or "").strip()
        ],
    }


